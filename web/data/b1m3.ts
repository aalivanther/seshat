// neue Rauchen», el deporte, la cita médica y la alimentación. La gramática
// ancla es el PASSIV PRÄSENS enseñado con Processing Instruction (VanPatten):
// el hispanohablante lee el primer sustantivo como agente («Der Patient wird
// von der Ärztin untersucht» → *«el paciente examina») y, sobre todo, traduce
// su «se» impersonal con `man` y NUNCA produce pasiva. Por eso las actividades
// referenciales usan frases REVERSIBLES (médica↔paciente, entrenador↔deportista)
// y el output es la transformación bidireccional man ↔ Passiv. Segundo bloque:
// el imperativo de consejo (Beweg dich! / Nehmen Sie die Treppe!) con su
// alternativa suave (Du solltest…, An deiner Stelle würde ich…).
