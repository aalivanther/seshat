// REFERENCIA — Los verbos del A1, todos en un sitio.
// Cada verbo del curso con su conjugación completa en presente, su Partizip
// (solo si el curso lo enseña — fases 9, 10 y 11) y la trampa típica del
// hispanohablante. Es tu libreta de consulta antes del examen.
//
// CONVENCIÓN para verbos separables: en `present` el prefijo va al final,
// separado con "...": "stehe ... auf" = «ich stehe um sieben Uhr auf».
// El prefijo SIEMPRE cierra la frase; lo demás queda en medio.
//
// CONVENCIÓN de `sound` (la del curso): sílabas con guiones, la tónica en
// MAYÚSCULAS; w = «v», z = «ts», ei = «ai», ie = «ii» (i larga), h = «j»
// suave, sch/sp/st = «sh», s + vocal = «z» (s sonora, zumbada), y las vocales
// con Umlaut se escriben tal cual: ö = «ö» (di «e» con boca de «o»), ü = «ü»
// (di «i» con boca de «u»).

