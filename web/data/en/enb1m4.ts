// Gramática ancla: LA PASIVA. Present simple, past simple y present perfect
// passive; «by» + agente y —sobre todo— cuándo el agente se calla; el
// get-passive en receptivo; y las TRES salidas inglesas del «se» impersonal
// español: pasiva, «you» genérico y «they/people». Es la trampa nº 4 del
// hispanohablante (PLAN-EN-B1 §3.1): el español resuelve con «se» lo que el
// inglés resuelve con pasiva, así que el alumno la ENTIENDE y no la produce
// jamás — exactamente igual que en alemán.
//
// Va aquí, antes de los módulos de opinión, porque «It is said that…» y «It
// has been shown that…» son ladrillos del argumento escrito, y porque el
// Reading Part 4 del examen es un texto expositivo o biográfico y ese género
// vive en pasiva (PLAN-EN-B1 §4.1). Aviso de norma, que consta: LanguageCert
// coloca la pasiva en B2 (handbook LRW §2.7), pero es B1 en el English Grammar
// Profile y contenido explícito de Cambridge B1 Preliminary; el propio examen
// dice que el candidato verá gramática del nivel de arriba aunque no se le
// pregunte. Renunciar a ella dejaría al alumno sin leer su propio examen.
//
// EXAM LAB (L10): Reading Part 4 — UN texto continuo y preguntas abiertas de
// respuesta escrita, máximo tres palabras. Es el cambio estructural más grande
// respecto al A2: ya no se puede aprobar el Reading adivinando. Gastados hasta
// aquí: Listening Part 1 (m1), Reading Part 1 (m2), Listening Part 3 (m3).
//
// Lo que este módulo NO reabre: las relativas son del m2 y el estilo indirecto
// completo es del m3 — se re-inyectan en la espiral de la L9, no se enseñan de
// nuevo. Tampoco se toca el léxico de empleo (salary, wage, income, prospects,
// overtime, permanent, temporary) ni el papeleo (CV, covering letter,
// reference, interview, vacancy, advert): son del m2 y se referencian por id.
//
