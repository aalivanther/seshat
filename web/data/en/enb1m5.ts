// INGLÉS B1 · MÓDULO 5 — If I Were You: dinero, hipótesis y el consejo que no
// ofende.
//
// Gramática ancla: segundo condicional (If I had…, I would…), el contraste
// REAL vs IRREAL con el primero, `I wish` / `If only` + pasado, `would rather`,
// `had better` y `should have` (receptivo). Campo léxico: el dinero de verdad
// —presupuesto, ahorro, deudas, devoluciones, garantías— que es el que sostiene
// la carta formal de queja del Writing Part 1.
//
// EL CALCO QUE ORDENA EL MÓDULO (PLAN-EN-B1 §3.1, fila 8, y §«contraste» nº 18):
// «If I would have money, I would travel». El `would` traduce el -ría del
// español y el alumno lo pone en las DOS mitades porque «si tuviera» no se
// parece a un presente. Por eso todos los `transform` de condicional de este
// módulo tocan LA MITAD DEL IF, nunca la frase entera: el error vive ahí y solo
// ahí. Los otros tres calcos del módulo son léxicos y van con su clínica:
//   (a) borrow / lend — «prestar» es un solo verbo en español;
//   (b) `pay for`, `spend on`, `ask for`, `charge for` — rección directa;
//   (c) «It doesn't worth it» por «It isn't worth it».
//
// LO QUE ESTE MÓDULO NO REABRE: el estilo indirecto quedó CERRADO en el m3
// (backshift, preguntas referidas, verbos introductorios, puntuación de la
// cita). Aquí se re-inyecta en la L9 espiral y en un solo `errorfix` de la
// inversión en pregunta indirecta —que Coe marca como problema «for
// intermediate and even advanced learners»—, pero no se vuelve a enseñar. Y el
// léxico de sueldo y papeleo de empleo es del m2: se referencia por id.
//
// CONECTORES: los libres del EVP que nadie se había llevado — `though` (final
// de frase, muy británico), `in spite of`, `in addition`, `on the other hand` y
// `all in all` / `to sum up`, que no tenía tarjeta en ninguna parte y es lo que
// pide el cierre del monólogo. `however` es A2 y `whereas`, `moreover`,
// `furthermore`, `as a result` e `in conclusion` son B2: no van como objetivo.
//
