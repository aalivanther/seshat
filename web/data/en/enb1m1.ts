// INGLÉS B1 · MÓDULO 1 — Two Years In: el balance de dos años en Londres.
// Es el PILOTO del nivel: fija el listón de los once que vienen detrás.
//
// Gramática ancla: present perfect simple vs past simple mandado por el
// marcador, present perfect continuous (How long have you been…?) y el reparto
// for / since / already / yet / just / still. Es la trampa nº1 del
// hispanohablante (PLAN-EN-B1 §3.1) porque el alumno mapea have+participio =
// he+participio 1:1 y se lo lleva hasta C1 si nadie interviene. OJO con cómo se
// explica: «he ido AYER» no es correcto tampoco en España —ayer cierra el
// periodo y pide indefinido en todas partes—; el sobreuso peninsular va con
// «hoy», «esta mañana», «este año». Y el sesgo se INVIERTE en Latinoamérica,
// que infrausa el perfecto. Por eso la nota del alumno lleva las dos mitades.
//
// Los tres calcos que fosilizan y que este módulo ataca de frente (§ «El
// contraste con el español», filas 11-14): (a) «desde hace» → «I live here
// since three years»; (b) el clítico de dativo con verbos de decir → «explain
// me», «say me»; (c) la posición del adverbio → «I like very much this flat»;
// (d) la rección directa del español → «depends of».
//
// Lo que este módulo NO enseña, a propósito: el backshift no es interferencia
// del español (el español también concuerda tiempos: «dijo que estaba
// cansado»), así que el estilo indirecto se guarda para el m3 y aquí solo entra
// say/tell, que sí falla. Y los conectores son los de B1 verificados en el EVP
// —although, though, despite, in spite of, unless, since causal, therefore,
// besides, for instance, of course—: «however» es A2 y «moreover»,
// «furthermore», «whereas», «as a result» son B2, no van como objetivo.
//
// RECICLADO del A1 inglés (sin redeclarar ni un id): enflat, enflatmate,
// enkitchen, enbedroom, enlivingroom, enhouse, enroom, enexpensive, encheap,
// enrent no existía, ennurse, enbusy, enwork, enjob, enmonth, enweek,
// enalways, ennever, enusually, ensometimes, enyesterday, enlastnight,
// enlondon, enathome, enhome, enbestreply, entwice, enrecording,
// enlistencarefully, enexcuseme, encanyourepeat, ensorryicant, enseeyousoon,
// enthankyou, endontworry, enwriteback, enbestwishes, endearamy, entooexpensive.
//
// CONVENCIÓN DE IDS: todos los ids nuevos llevan el prefijo del módulo
// (enb1m1…). El A1 inglés está exento a propósito (enhello, enbreakfast: ya
// viajaron en los drops 3 y 4 y son claves de progreso vivas), pero desde el A2
// el validador lo exige y los doce módulos del B1 se escriben en paralelo: sin
// prefijo, dos módulos acaban enseñando la misma palabra por separado.

