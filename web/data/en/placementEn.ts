// INGLÉS · EXAMEN DE COLOCACIÓN — 68 ítems en dificultad creciente (12 A1,
// 14 A2, 14 B1, 14 B2, 14 C1) para situar a quien llega de fuera: no solo QUÉ
// nota saca, sino QUÉ domina, qué entiende a medias y dónde está flojo.
//
// Mide hasta el C1 aunque el curso llegue al A1, y a propósito: el informe
// tiene que servir para entrar en cualquier escuela o para saber qué reforzar,
// y lo que aquí se dice ha de poder sostenerse delante de un examinador. Por
// eso el B2 y el C1 no son «B1 con palabras difíciles»: lo que separan es el
// registro exacto, la colocación natural, la inferencia y la ironía.
//
// Cómo está construido (y por qué):
//   · Cada ítem mide UNA cosa y lleva su etiqueta `topic`. Cada tema aparece
//     como mínimo DOS veces: un diagnóstico que depende de una sola respuesta
//     no es un diagnóstico, es una moneda al aire.
//   · Los distractores no son ruido: cada opción falsa es un error real y
//     documentado del hispanohablante (la -s perdida, «Is raining», «the
//     people is», «more big», «since two years»…). El campo `trap` dice cuál,
//     para que el informe pueda hablar de errores y no de porcentajes.
//   · Una sola respuesta defendible por ítem. En los `cloze`, `answers` trae
//     TODAS las variantes que se dan por buenas.
//
// Contrato de los campos según `kind`:
//   · "mc"    → `options` + `answer` (índice de la correcta). `text` opcional:
//               el enunciado inglés, con ___ si hay hueco.
//   · "cloze" → `text` con ___ y `answers` = variantes aceptadas de ESE hueco.
//   · "order" → `options` = las fichas tal como se muestran (desordenadas) y
//               `answers` = la secuencia correcta.
//   · "listening" → `audio` es el texto que lee la voz; la pregunta va en
//                   `prompt`, en español, para no medir lectura sin querer.
//
// Sobre el canon: este examen queda FUERA de la ficción del curso a propósito
// —lo hace gente que aún no ha empezado—, así que no usa a ningún personaje
// del elenco. Los nombres que salen son de un solo uso y no reaparecen.
//
// Inglés británico en todo: ortografía (-ise/-our), léxico (flat, lift,
// chemist's, surgery, at the weekend) y puntuación (Mr/Mrs sin punto).

