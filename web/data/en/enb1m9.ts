// futuro con matices.
//
// El temario oficial de B1 abre dos campos que en A1 y A2 no existían: `travel
// documents` y `entering and leaving a country`. Y trae con ellos la trampa de
// tiempo verbal más cara del nivel para un hispanohablante: la oración temporal.
// «En cuanto llegue» es subjuntivo en español y PRESENTE en inglés —*as soon as
// I get there*—, nunca futuro. La forma se calca bien; el tiempo, no. Por eso
// este módulo va después de que el alumno domine los futuros: primero se
// aprenden los cuatro, y solo después se le quita el futuro a la mitad de las
// frases donde el español lo pediría.
//
// Gramática ancla: (a) los CUATRO FUTUROS contrastados —will, going to, present
// continuous y present simple de horarios— más el *future continuous* en modo
// receptivo (la megafonía habla así: *we'll be boarding shortly*); (b) las
// TEMPORALES SIN FUTURO —as soon as, until, by the time, once, before, after—;
// y (c) la condición con matiz: *unless* (que ya trae del m1) frente a *as long
// as* y *provided (that)*, más *in case*, que es otro calco de manual («por si
// acaso» + subjuntivo → *in case* + presente).
