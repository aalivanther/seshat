// all the / most of the / both / neither / either, y el bloque que da nombre al
// módulo: los conectores de CONTRASTE y CONCESIÓN.
//
// EL REPARTO DE CONECTORES, QUE ES LA DECISIÓN DE FONDO DE ESTE MÓDULO.
// El nivel real de cada conector está verificado en el English Vocabulary
// Profile y casi todo el mundo lo pone donde no es:
//   · B1 (producción, lo que el alumno tiene que SACAR): although, though,
//     even though, in spite of, despite, unless, while, since causal,
//     therefore, otherwise, besides, for instance, due to.
//   · A2 (ya está por debajo del nivel, así que es gratis): however. Se enseña,
//     se reconoce y se ofrece en los bancos de escritura, pero la nota de este
//     módulo no depende de él.
//   · B2 (reconocimiento y nada más, con su aviso en voz alta): whereas,
//     moreover, furthermore, as a result, in conclusion, nevertheless. Aparecen
//     en textos y en ejercicios de opción múltiple; NO se pide producirlos y no
//     tienen tarjeta de vocabulario, porque una tarjeta entra al SRS y el SRS
//     acaba pidiendo producir.
//
// Y una consecuencia práctica: los conectores B1 de arriba YA TIENEN TARJETA en
// los módulos 1 y 2 (enb1m1although, enb1m1despite, enb1m1therefore,
// enb1m1besides, enb1m1unless, enb1m1forinstance, enb1m2while,
// enb1m2sincecausal, enb1m2otherwise, enb1m2dueto). Este módulo NO los vuelve a
// declarar: los referencia por su id y los pone a trabajar. Eso es, además, la
// hebra de fluidez de Nation —velocidad sobre material ya visto— sin inventarse
// nada. Lo único nuevo del bloque es lo que no existía: `even though`,
// `however` y las dos construcciones que se calcan mal, `despite + -ing` e
// `instead of + -ing`.
//
