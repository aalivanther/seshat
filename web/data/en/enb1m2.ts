// INGLÉS B1 · MÓDULO 2 — The Job I Want: sueldo, perspectivas y la máquina de
// alargar frases.
//
// Gramática ancla: la ORACIÓN DE RELATIVO. Especificativas con who / which /
// that, el relativo OMITIDO (the job I applied for), la preposición al final
// (the person I work with), whose / where / when, y las explicativas con comas.
// Es lo que el handbook de LanguageCert llama «complex sentences with one
// subordinate clause» y «noun phrases with pre- and post-modification»
// (PLAN-EN-B1 §2.1): sin relativas no hay Reading Part 2, no hay definiciones y
// el Writing se queda en frases cortas encadenadas con «and».
//
// Los calcos que este módulo ataca de frente (PLAN-EN-B1, «El contraste con el
// español», fila 25): (a) el pronombre reasumido —«the man that I saw HIM», «the
// city where I live IN IT»—, que el español coloquial admite; (b) el relativo
// que NUNCA se omite en español y en inglés sí, y por eso el alumno jamás
// produce «the job I applied for»; (c) «that» colado en la explicativa, donde
// solo cabe «which»/«who»; (d) «lo que» traducido por «what» («I start at six,
// what means…»); y (e) la rección: apply FOR, good AT, responsible FOR.
//
// Lo que este módulo NO enseña, a propósito: nada de estilo indirecto (m3) ni
// de pasiva (m4). Y los conectores nuevos son los seis de B1 verificados en el
// EVP que el m1 no gastó —while, since causal, otherwise, due to, at least,
// apart from—: «however» es A2 y «whereas», «moreover», «furthermore», «as a
// result» y «in conclusion» son B2, así que no van como objetivo del nivel.
//
// EXAM LAB (L10): Reading Part 1 — cinco textos cortos con un hueco cada uno y
// MC de 3, donde se prueban «layout, lexis, cohesive devices, coherence».
//
