// INGLÉS B1 · MÓDULO 3 — What They Said: contar lo que otro dijo, y preguntar
// sin sonar brusco.
//
// Gramática ancla: estilo indirecto entero (say/tell/ask, desplazamiento de
// tiempos, cambios de persona, tiempo y lugar), preguntas referidas SIN
// inversión y SIN do, preguntas incrustadas de cortesía (Could you tell me
// where the station is?), los verbos introductorios del nivel (explain, admit,
// suggest, promise, complain, apologise, warn, point out, announce, mention) y
// la puntuación del estilo directo, que en LanguageCert puntúa dentro del
// criterio `Organisation`.
//
// LO QUE ESTE MÓDULO NO ENSEÑA MAL, Y CONVIENE QUE SIGA ASÍ (PLAN-EN-B1, A.8):
// el desplazamiento de tiempos NO es interferencia del español. «Dijo que
// estaba cansado» concuerda igual que «He said he was tired», así que aquí se
// presenta como una mecánica, no como un calco. Los calcos de verdad —los que
// Coe documenta y los que se cobran en la nota— son otros tres y llevan la
// clínica entera del módulo:
//   (a) say/tell: «He said me that…», porque «me dijo» no distingue;
//   (b) la INVERSIÓN en la pregunta referida: «I don't know where is the
//       station» / «She asked me where was the station» — problema «for
//       intermediate and even advanced learners»;
//   (c) las órdenes y peticiones referidas, que el español resuelve con
//       subjuntivo: «They ordered her that she went» por «asked her to go».
//
// Conectores: los del B1 verificados en el EVP que el m1 NO se llevó — anyway,
// at least, actually (contraste con lo esperado), after all —, más los suyos
// referenciados por id. «however» es A2 y «moreover», «whereas», «as a result»,
// «in conclusion» son B2: no van como objetivo en ningún ejercicio.
//
