// EXAMEN DE COLOCACIÓN · ALEMÁN — para quien llega de fuera y no sabe por dónde
// entrar en el curso. No es un examen del curso: es una MEDIDA. Contenido
// nuevo, escrito para esto; nadie puede aprobarlo por habérselo estudiado antes.
//
// Cómo está construido (y por qué así):
//
// · 68 ítems en dificultad creciente — 12 de A1, 14 de A2, 14 de B1, 14 de B2
//   y 14 de C1. El `level` NO es el nivel del alumno: es el nivel que MIDE el
//   ítem. Quien acierta lo de A1 y falla lo de A2 se sitúa solo.
// · Se mide hasta C1 aunque el curso llegue al B1, y a propósito: quien ya está
//   por encima del techo del curso merece saberlo, y con un banco que solo
//   llegara al B1 el resultado sería siempre el mismo («B1 y de sobra»), que no
//   informa de nada. Con B2 y C1 dentro, el informe se puede enseñar en una
//   escuela: dice lo mismo que diría una prueba de colocación certificada.
// · Cada ítem mide UNA cosa, su `topic`, y ningún `topic` aparece una sola vez:
//   dos ítems por tema como mínimo, para que un acierto de suerte o un despiste
//   no decidan un diagnóstico. Con dos ítems se puede decir «lo domina» (2/2),
//   «a medias» (1/2) o «flojo» (0/2), que es justo lo que hay que devolverle.
// · Los distractores no son relleno: cada opción incorrecta es un error real y
//   frecuente del hispanohablante, y `trap` dice cuál. Un distractor que nadie
//   elige no informa de nada.
// · Es un examen de entrada: va escrito en neutro, sin personajes del curso, y
//   nadie que lo haga necesita conocer a nadie de Berlín para responder.
//
// Contrato con el motor, por tipo de ítem:
//
//   "mc"    → `options` (3 opciones) y `answer` con el índice correcto.
//   "cloze" → `text` lleva ___ donde va el hueco; `answers` trae TODAS las
//             variantes que se dan por buenas. `isCorrect` compara recortando
//             espacios y sin distinguir mayúsculas, así que ahí no hay trampa.
//   "order" → hoy la página resuelve todo lo que no es "mc" con un campo de
//             texto: `options` NO se pinta. Por eso las fichas van también
//             escritas en el `prompt` —si algún día hay interfaz de fichas,
//             `options` ya está— y `answers` guarda la FRASE entera, que es lo
//             que el alumno teclea y lo que `isCorrect` compara. Cuando solo se
//             ordena un trozo, `text` enseña el resto con ___ en su sitio.
//
// Los `topic` se apoyan en los que ya traduce `TOPIC_LABEL` (lib/placement.ts).
// Los de A1–B1 que faltan en esa tabla —praesens, alltagswortschatz,
// falschefreunde, globalverstehen y detailverstehen— y todos los de B2/C1
// —konjunktiv1, partizipialkonstruktionen, nominalisierung, konnektoren-formell,
// funktionsverbgefuege, passiversatz, modalpartikeln, genus-verbi, wortbildung,
// idiomatik, registerwechsel, konzessiv e irreale-vergleiche— se enseñan crudos
// hasta que se añadan allí, que es lo que hace `topicLabel` con lo que no
// conoce. La etiqueta cruda es fea, pero es preferible a una inventada.
//
// El `audio` de los ítems de "hoeren" es el texto que lee la voz sintética: NO
// se le enseña al alumno por escrito (por eso esos ítems no llevan `text`). La
// pregunta va siempre en español, para no medir de rebote la comprensión de la
// consigna.

export interface PlacementItem {
  id: string;
  /** el nivel que MIDE el ítem, no el del alumno */
  level: "a1" | "a2" | "b1" | "b2" | "c1";
  skill: "lesen" | "hoeren" | "wortschatz" | "grammatik";
  /** etiqueta corta y estable: es lo que el alumno verá en su informe */
  topic: string;
  kind: "mc" | "cloze" | "order";
  /** la consigna, en español */
  prompt: string;
  /** el enunciado alemán (con ___ si es cloze o si «order» ordena un trozo) */
  text?: string;
  /** solo para "hoeren": lo que lee la voz; nunca se muestra escrito */
  audio?: string;
  options?: string[];
  answer?: number;
  answers?: string[];
  /** por qué es esa, en una línea */
  why: string;
  /** el calco del hispanohablante que este ítem está midiendo */
  trap?: string;
}

